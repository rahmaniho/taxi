export default {
    id: 'training',
    title: 'آموزش',

    render(view) {
        view.innerHTML = `
        <section class="page-section active">
          ${pageHeader({
            title: 'آموزش و راهنما', iconName: 'book',
            subtitle: 'راهنمای گام‌به‌گام برای اپراتور، حسابدار و مدیر به‌همراه پرسش‌های پرتکرار.'
          })}
          <div class="alert-row info mb-16">${icon('info')} نقش فعال شما: <b>${ROLE_LABELS[Auth.role()] || '—'}</b> — راهنمای مربوط به نقش شما در ابتدای فهرست قرار گرفته است.</div>

          <div class="tab-lite mb-16" id="trTabs">
            ${GUIDES.map((g, i) => `<button type="button" data-guide="${g.id}" class="${i === 0 ? 'active' : ''}">${icon(g.iconName)} ${g.title}</button>`).join('')}
            <button type="button" data-guide="faq">${icon('help')} پرسش‌های پرتکرار</button>
          </div>

          <div id="trBody"></div>
        </section>`;

        const root = view.querySelector('.page-section');
        const body = root.querySelector('#trBody');

        const renderGuide = (guideId) => {
            if (guideId === 'faq') {
                body.innerHTML = `<div class="card"><div class="card-header"><div class="card-title">${icon('help')} پرسش‌های پرتکرار</div></div>
                  ${FAQ.map(([q, a], i) => `<div class="faq-item">
                    <div class="faq-q" data-faq="${i}">${icon('chevron-left')} ${escapeHTML(q)}</div>
                    <div class="faq-a" id="faqA${i}">${escapeHTML(a)}</div>
                  </div>`).join('')}</div>`;
                body.querySelectorAll('.faq-q').forEach((q) => q.addEventListener('click', () => {
                    const a = body.querySelector('#faqA' + q.dataset.faq);
                    const open = a.classList.toggle('open');
                    q.classList.toggle('open', open);
                    q.querySelector('svg')?.classList.toggle('rot-90', open);
                }));
                return;
            }
            const g = GUIDES.find((x) => x.id === guideId) || GUIDES[0];
            body.innerHTML = `
              <div class="card mb-16">
                <div class="card-header">
                  <div class="card-title" style="color:${g.color}">${icon(g.iconName)} ${g.title}</div>
                  <span class="chip">${icon('list')} ${toFa(g.steps.length)} گام</span>
                </div>
                <p class="mb-14">${escapeHTML(g.intro)}</p>
                <div class="steps-timeline">
                  ${g.steps.map(([t, d], i) => `
                    <div class="timeline-item">
                      <div class="timeline-dot">${toFa(i + 1)}</div>
                      <div class="timeline-body">
                        <div class="timeline-title">${escapeHTML(t)}</div>
                        <div class="timeline-text">${escapeHTML(d)}</div>
                      </div>
                    </div>`).join('')}
                </div>
              </div>
              <div class="card">
                <div class="card-header"><div class="card-title">${icon('check-circle')} چک‌لیست پایان کار</div></div>
                <ul class="checklist" data-role="${g.id}">
                  ${checklistFor(g.id).map((c, i) => `<li><label><input type="checkbox" class="chk" data-chk="${g.id}-${i}"> ${escapeHTML(c)}</label></li>`).join('')}
                </ul>
              </div>`;
            // بازگردانی وضعیت چک‌لیست
            body.querySelectorAll('[data-chk]').forEach((c) => {
                if (localStorage.getItem('taxi_check_' + c.dataset.chk) === '1') c.checked = true;
                c.addEventListener('change', () => localStorage.setItem('taxi_check_' + c.dataset.chk, c.checked ? '1' : '0'));
            });
        };

        root.querySelector('#trTabs').addEventListener('click', (e) => {
            const b = e.target.closest('[data-guide]');
            if (!b) return;
            root.querySelectorAll('#trTabs button').forEach((x) => x.classList.toggle('active', x === b));
            renderGuide(b.dataset.guide);
        });

        const roleGuide = { admin: 'admin', accountant: 'accountant', operator: 'operator' }[Auth.role()] || 'operator';
        root.querySelectorAll('#trTabs button').forEach((x) => x.classList.toggle('active', x.dataset.guide === roleGuide));
        renderGuide(roleGuide);
    }
};

function checklistFor(role) {
    if (role === 'operator') return [
        'شروع شیفت با ثبت صندوق اولیه',
        'پاسخ به تماس‌ها و ثبت سفرها',
        'تخصیص راننده به همه سفرهای در انتظار',
        'بستن وضعیت سفرهای پایان‌یافته',
        'ثبت دلیل برای همه لغوها',
        'پایان شیفت و چاپ گزارش تحویل صندوق'
    ];
    if (role === 'accountant') return [
        'بررسی طلب/بدهی رانندگان و تسویه‌های باقی‌مانده',
        'ثبت پرداخت مشترکین بدهکار',
        'پیگیری بدهی‌های بیش از ۶۰ روز',
        'ثبت هزینه‌های روز',
        'تهیه گزارش مالی ماهانه و ارسال به مدیر'
    ];
    return [
        'تعیین تعرفه پایه، نرخ کیلومتر و ضریب‌های شب/تعطیلات',
        'ثبت تعطیلات رسمی سال',
        'ساخت کاربر برای اپراتورها و حسابدار با نقش درست',
        'بررسی گزارش تغییرات (حسابرسی)',
        'پشتیبان‌گیری هفتگی از داده‌ها'
    ];
}
